"""Acquisition data model, adapter interface and error taxonomy.

Adapters deliver raw samples in physical units. They do not filter, fan out,
or decide on reconnection; those belong to the acquisition service and
downstream consumers.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from dataclasses import dataclass
from typing import Literal, Protocol

import numpy as np

ChannelType = Literal["EEG", "EOG", "EMG", "ECG", "MISC"]
SignalUnit = Literal["uV"]
TimestampSource = Literal["synthetic-nominal", "host-receipt-fitted", "device-clock"]


class AcquisitionError(Exception):
    """Base class for adapter errors. `retryable` drives reconnection."""

    code = "acquisition-error"
    retryable = False


class DeviceConfigError(AcquisitionError):
    """The requested configuration is invalid. Never retried."""

    code = "invalid-device-config"


class DeviceConnectionError(AcquisitionError):
    """The device could not be opened."""

    code = "device-connection-failed"
    retryable = True


class DeviceDisconnectedError(AcquisitionError):
    """An open device stopped delivering data."""

    code = "device-disconnected"
    retryable = True


@dataclass(frozen=True, slots=True)
class ChannelSpec:
    label: str
    reference: str
    type: ChannelType = "EEG"
    unit: SignalUnit = "uV"


@dataclass(frozen=True, slots=True)
class DeviceInfo:
    kind: str
    model: str
    device_id: str
    adapter_version: str
    firmware_version: str | None = None


@dataclass(frozen=True, slots=True)
class SyntheticProvenance:
    """Signal is generated by software, not measured from a person."""

    generator: str
    generator_version: str
    seed: int
    config_hash: str


@dataclass(frozen=True, slots=True)
class DeviceProvenance:
    """Signal is measured by a physical device."""


@dataclass(frozen=True, slots=True)
class StreamDescriptor:
    """Static description of what an opened adapter will deliver."""

    device: DeviceInfo
    channels: tuple[ChannelSpec, ...]
    nominal_sample_rate_hz: float
    timestamp_source: TimestampSource
    provenance: SyntheticProvenance | DeviceProvenance

    def __post_init__(self) -> None:
        if not self.channels:
            raise DeviceConfigError("a stream needs at least one channel")
        labels = [channel.label for channel in self.channels]
        if len(set(labels)) != len(labels):
            raise DeviceConfigError("channel labels must be unique")
        if not np.isfinite(self.nominal_sample_rate_hz) or self.nominal_sample_rate_hz <= 0:
            raise DeviceConfigError("nominal sample rate must be positive and finite")

    @property
    def channel_count(self) -> int:
        return len(self.channels)


@dataclass(frozen=True, slots=True)
class SampleBlock:
    """Immutable, contiguous block of raw samples from an adapter.

    `data` is a read-only float64 array shaped (channels, samples) in each
    channel's declared unit. `first_sample_index` comes from the device's own
    counter (or the generator), never from arrival order.
    `device_timestamps_us` optionally preserves raw per-sample device/host
    timestamps for the future recorder; it is not sent to live-view clients.
    """

    first_sample_index: int
    first_sample_time_us: int
    data: np.ndarray
    device_timestamps_us: np.ndarray | None = None

    def __post_init__(self) -> None:
        data = np.array(self.data, dtype=np.float64, copy=True)
        if data.ndim != 2 or data.shape[0] < 1 or data.shape[1] < 1:
            raise ValueError("sample data must be shaped (channels, samples) with both > 0")
        if self.first_sample_index < 0:
            raise ValueError("first_sample_index must be non-negative")
        data.setflags(write=False)
        object.__setattr__(self, "data", data)
        if self.device_timestamps_us is not None:
            stamps = np.array(self.device_timestamps_us, dtype=np.int64, copy=True)
            if stamps.shape != (data.shape[1],):
                raise ValueError("device_timestamps_us must have one entry per sample")
            stamps.setflags(write=False)
            object.__setattr__(self, "device_timestamps_us", stamps)

    @property
    def channel_count(self) -> int:
        return int(self.data.shape[0])

    @property
    def sample_count(self) -> int:
        return int(self.data.shape[1])


@dataclass(frozen=True, slots=True)
class ActiveStream:
    """A stream opened by the acquisition service.

    The anchor pairs the engine monotonic clock with UTC at stream open.
    """

    stream_id: str
    descriptor: StreamDescriptor
    anchor_monotonic_us: int
    anchor_unix_time_us: int


@dataclass(frozen=True, slots=True)
class StreamBlock:
    """A SampleBlock accepted into a stream, with stream-level counters."""

    stream_id: str
    block_sequence: int
    dropped_samples_before: int
    block: SampleBlock


class DeviceAdapter(Protocol):
    """Interface implemented by every acquisition source (synthetic, device, replay).

    Lifecycle: `open()` once, iterate `blocks()` until it ends or raises, then
    `close()` (idempotent, always called by the service). Adapters are single-use.
    """

    async def open(self) -> StreamDescriptor:
        """Connect and configure. Raises DeviceConfigError or DeviceConnectionError."""
        ...

    def blocks(self) -> AsyncIterator[SampleBlock]:
        """Yield blocks in acquisition order. Raises DeviceDisconnectedError."""
        ...

    async def close(self) -> None: ...
